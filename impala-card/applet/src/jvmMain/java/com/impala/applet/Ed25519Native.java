package com.impala.applet;

import javacard.framework.JCSystem;
import javacard.framework.SystemException;
import javacard.framework.Util;
import javacard.security.CryptoException;
import javacard.security.KeyBuilder;
import javacard.security.KeyPair;
import javacard.security.MessageDigest;
import javacard.security.NamedParameterSpec;
import javacard.security.Signature;
import javacard.security.XECPrivateKey;
import javacard.security.XECPublicKey;
import javacardx.crypto.Cipher;

/**
 * Ed25519 on JavaCard 3.1 and 3.2 platforms: the card's own EdDSA over
 * {@code NamedParameterSpec.ED25519} keys. The key pair is generated by the
 * platform and the private key never leaves its key object.
 *
 * <p>Platforms offer pure Ed25519 in more than one way, so the engine does
 * not guess. There are three requests a card may answer:</p>
 * <ol>
 *   <li>the generic cipher {@code Signature.SIG_CIPHER_EDDSA} with
 *       {@code MessageDigest.ALG_NULL} (what the JavaCard 3.2 text says a
 *       caller must pass);</li>
 *   <li>the same cipher with {@code MessageDigest.ALG_SHA_512} (the JavaCard
 *       3.1 text did not name the digest constant, and platforms differ);</li>
 *   <li>the per-curve cipher {@code SIG_CIPHER_EDDSA_ED25519} that JavaCard
 *       3.2 adds, with {@code ALG_NULL}: a 3.2 platform may have Ed25519
 *       under that name only.</li>
 * </ol>
 * <p>At construction the engine tries them in that order and keeps the first
 * one that verifies an RFC 8032 test vector AND, with that vector's private
 * key loaded, signs the same message into a signature that verifies.
 * Verification alone would leave the signing path unproven. A platform on
 * which no candidate does both gets no engine ({@link #create()} returns
 * null) and the card works as a legacy card, rather than one that emits
 * signatures nobody else can verify. The card's own key is generated
 * afterwards and never signs a test message. The order keeps the choice on a
 * JavaCard 3.1 card what it always was: the 3.2 cipher is asked for only
 * where the generic one is not pure Ed25519.</p>
 *
 * <p>Signing is the platform's: RFC 8032 nonces are deterministic, without the
 * fresh randomness {@link Ed25519Soft} mixes in, so resistance to fault
 * attacks on the nonce is whatever the platform provides.</p>
 *
 * <p>This class needs the JavaCard 3.1 API. It is compiled into the CAP only
 * for {@code -Papplet.ed25519=native}.</p>
 */
final class Ed25519Native extends Ed25519 {
    // RFC 8032 section 7.1, TEST 2: private key, public key, one-byte message, signature.
    private static final byte[] KAT_PRIVATE = {
            (byte) 0x4C, (byte) 0xCD, (byte) 0x08, (byte) 0x9B, (byte) 0x28, (byte) 0xFF, (byte) 0x96, (byte) 0xDA,
            (byte) 0x9D, (byte) 0xB6, (byte) 0xC3, (byte) 0x46, (byte) 0xEC, (byte) 0x11, (byte) 0x4E, (byte) 0x0F,
            (byte) 0x5B, (byte) 0x8A, (byte) 0x31, (byte) 0x9F, (byte) 0x35, (byte) 0xAB, (byte) 0xA6, (byte) 0x24,
            (byte) 0xDA, (byte) 0x8C, (byte) 0xF6, (byte) 0xED, (byte) 0x4F, (byte) 0xB8, (byte) 0xA6, (byte) 0xFB
    };
    private static final byte[] KAT_PUBLIC = {
            (byte) 0x3D, (byte) 0x40, (byte) 0x17, (byte) 0xC3, (byte) 0xE8, (byte) 0x43, (byte) 0x89, (byte) 0x5A,
            (byte) 0x92, (byte) 0xB7, (byte) 0x0A, (byte) 0xA7, (byte) 0x4D, (byte) 0x1B, (byte) 0x7E, (byte) 0xBC,
            (byte) 0x9C, (byte) 0x98, (byte) 0x2C, (byte) 0xCF, (byte) 0x2E, (byte) 0xC4, (byte) 0x96, (byte) 0x8C,
            (byte) 0xC0, (byte) 0xCD, (byte) 0x55, (byte) 0xF1, (byte) 0x2A, (byte) 0xF4, (byte) 0x66, (byte) 0x0C
    };
    private static final byte[] KAT_MESSAGE = {
            (byte) 0x72
    };
    /**
     * {@code Signature.SIG_CIPHER_EDDSA_ED25519}, the per-curve cipher of the
     * JavaCard 3.2 API. Spelled out because this class is converted against
     * the JavaCard 3.1 API, which has no such name: the value is what the
     * card is asked for at run time, and a card that does not know it
     * answers {@code NO_SUCH_ALGORITHM}. So one CAP serves 3.1 and 3.2 cards.
     */
    static final byte SIG_CIPHER_EDDSA_ED25519 = (byte) 15;

    private static final byte[] KAT_SIGNATURE = {
            (byte) 0x92, (byte) 0xA0, (byte) 0x09, (byte) 0xA9, (byte) 0xF0, (byte) 0xD4, (byte) 0xCA, (byte) 0xB8,
            (byte) 0x72, (byte) 0x0E, (byte) 0x82, (byte) 0x0B, (byte) 0x5F, (byte) 0x64, (byte) 0x25, (byte) 0x40,
            (byte) 0xA2, (byte) 0xB2, (byte) 0x7B, (byte) 0x54, (byte) 0x16, (byte) 0x50, (byte) 0x3F, (byte) 0x8F,
            (byte) 0xB3, (byte) 0x76, (byte) 0x22, (byte) 0x23, (byte) 0xEB, (byte) 0xDB, (byte) 0x69, (byte) 0xDA,
            (byte) 0x08, (byte) 0x5A, (byte) 0xC1, (byte) 0xE4, (byte) 0x3E, (byte) 0x15, (byte) 0x99, (byte) 0x6E,
            (byte) 0x45, (byte) 0x8F, (byte) 0x36, (byte) 0x13, (byte) 0xD0, (byte) 0xF1, (byte) 0x1D, (byte) 0x8C,
            (byte) 0x38, (byte) 0x7B, (byte) 0x2E, (byte) 0xAE, (byte) 0xB4, (byte) 0x30, (byte) 0x2A, (byte) 0xEE,
            (byte) 0xB0, (byte) 0x0D, (byte) 0x29, (byte) 0x16, (byte) 0x12, (byte) 0xBB, (byte) 0x0C, (byte) 0x00
    };

    private final XECPrivateKey privateKey;
    private final XECPublicKey publicKey;
    private final KeyPair keyPair;
    private final Signature signature;
    private final byte[] pub;           // RFC 8032 public key
    private boolean generated;          // pub holds a public key
    private boolean ready;              // the private half is present

    private Ed25519Native() {
        NamedParameterSpec curve = NamedParameterSpec.getInstance(NamedParameterSpec.ED25519);
        privateKey = (XECPrivateKey) KeyBuilder.buildXECKey(curve,
                (short) (JCSystem.MEMORY_TYPE_PERSISTENT | KeyBuilder.ATTR_PRIVATE), false);
        publicKey = (XECPublicKey) KeyBuilder.buildXECKey(curve,
                (short) (JCSystem.MEMORY_TYPE_PERSISTENT | KeyBuilder.ATTR_PUBLIC), false);
        if (publicKey.getEncodingLength() != PUBLIC_KEY_LENGTH) {
            CryptoException.throwIt(CryptoException.NO_SUCH_ALGORITHM);
        }
        // One install-time buffer for the self-test's signature. It is
        // persistent on purpose: transient memory is the scarce kind, and this
        // is written at most twice, here.
        byte[] probe = new byte[SIGNATURE_LENGTH];
        Signature candidate = pureEdDsa(MessageDigest.ALG_NULL, Signature.SIG_CIPHER_EDDSA, probe);
        if (candidate == null) {
            candidate = pureEdDsa(MessageDigest.ALG_SHA_512, Signature.SIG_CIPHER_EDDSA, probe);
        }
        if (candidate == null) {
            candidate = pureEdDsa(MessageDigest.ALG_NULL, SIG_CIPHER_EDDSA_ED25519, probe);
        }
        // The self-test left its test keys in the key objects.
        privateKey.clearKey();
        publicKey.clearKey();
        if (candidate == null) {
            CryptoException.throwIt(CryptoException.NO_SUCH_ALGORITHM);
        }
        signature = candidate;
        keyPair = new KeyPair(publicKey, privateKey);
        pub = new byte[PUBLIC_KEY_LENGTH];
        generated = false;
        ready = false;
    }

    /**
     * An EdDSA instance for this cipher and message digest constant, or null
     * unless it is pure Ed25519 in both directions: it verifies the RFC 8032
     * vector, which only pure Ed25519 does (the vector fails under Ed25519ph
     * and Ed25519ctx), and with the vector's private key it signs the same
     * message into a signature that the same check accepts. The second half
     * is a verification, not a byte comparison, so a platform that randomizes
     * its nonce still passes; one that will not load a private key does not.
     * Whatever a platform throws for a request it does not know counts as "no":
     * a probe must never be what stops the applet from installing.
     */
    private Signature pureEdDsa(byte messageDigest, byte cipher, byte[] probe) {
        try {
            Signature s = Signature.getInstance(messageDigest, cipher, Cipher.PAD_NULL, false);
            publicKey.setEncoded(KAT_PUBLIC, (short) 0, PUBLIC_KEY_LENGTH);
            s.init(publicKey, Signature.MODE_VERIFY);
            if (!s.verify(KAT_MESSAGE, (short) 0, (short) 1,
                    KAT_SIGNATURE, (short) 0, SIGNATURE_LENGTH)) {
                return null;
            }
            privateKey.setEncoded(KAT_PRIVATE, (short) 0, (short) KAT_PRIVATE.length);
            s.init(privateKey, Signature.MODE_SIGN);
            if (s.sign(KAT_MESSAGE, (short) 0, (short) 1, probe, (short) 0) != SIGNATURE_LENGTH) {
                return null;
            }
            s.init(publicKey, Signature.MODE_VERIFY);
            if (s.verify(KAT_MESSAGE, (short) 0, (short) 1, probe, (short) 0, SIGNATURE_LENGTH)) {
                return s;
            }
        } catch (Exception e) {
            // not offered in this form
        }
        return null;
    }

    /** The engine, or null when the platform has no pure Ed25519. */
    static Ed25519 create() {
        try {
            return new Ed25519Native();
        } catch (CryptoException e) {
            return null;
        } catch (SystemException e) {
            return null;
        }
    }

    byte engineId() {
        return ENGINE_NATIVE;
    }

    boolean hasPublicKey() {
        return generated;
    }

    boolean isKeyReady() {
        return ready;
    }

    void getPublicKey(byte[] out, short outOff) {
        Util.arrayCopyNonAtomic(pub, (short) 0, out, outOff, PUBLIC_KEY_LENGTH);
    }

    boolean generateKeyPair() {
        ready = false;
        generated = false;
        try {
            keyPair.genKeyPair();
            if (!privateKey.isInitialized() || !publicKey.isInitialized()) {
                return false;
            }
            publicKey.getEncoded(pub, (short) 0);
            generated = true;
            ready = true;
            return true;
        } catch (CryptoException e) {
            return false;
        }
    }

    short sign(byte[] msg, short msgOff, short msgLen, byte[] sig, short sigOff) {
        if (!ready) {
            CryptoException.throwIt(CryptoException.UNINITIALIZED_KEY);
        }
        signature.init(privateKey, Signature.MODE_SIGN);
        short n = signature.sign(msg, msgOff, msgLen, sig, sigOff);
        if (n != SIGNATURE_LENGTH) {
            CryptoException.throwIt(CryptoException.ILLEGAL_VALUE);
        }
        return n;
    }

    void clearKey() {
        ready = false;
        privateKey.clearKey();
    }
}
